-- ═════ BLOCO 2 — checklist de documentos e exames da admissão, por colaborador ═════
create table if not exists public.rh_admissao_itens (
  id uuid primary key default gen_random_uuid(),
  empresa_id uuid not null references public.empresas(id) on delete cascade,
  colaborador_id uuid not null references public.rh_colaboradores(id) on delete cascade,
  categoria text not null check (categoria in ('documento','exame')),
  tipo text not null check (tipo in ('ctps_digital', 'documento_identidade', 'cpf', 'comprovante_residencia', 'titulo_eleitor', 'reservista', 'certidao_civil', 'comprovante_escolaridade', 'certidao_filhos', 'vacinacao_filhos', 'frequencia_escolar_filhos', 'declaracao_dependentes_ir', 'opcao_vale_transporte', 'dados_bancarios', 'cnh_profissional', 'registro_profissional', 'contrato_assinado', 'ciencia_lgpd', 'aso_admissional', 'audiometria', 'espirometria', 'raio_x_torax', 'acuidade_visual', 'hemograma', 'eletrocardiograma', 'eletroencefalograma', 'toxicologico', 'outro_exame_pcmso')),
  situacao text not null default 'pendente' check (situacao in ('pendente','entregue','dispensado')),
  data_item date,                                            -- entrega do documento / realização do exame
  validade date,
  resultado text check (resultado in ('apto','inapto','apto_com_restricao')),   -- só ASO
  observacao text check (char_length(observacao) <= 500),
  updated_at timestamptz not null default now(),
  updated_by uuid default auth.uid(),
  constraint rh_adm_item_unico unique (colaborador_id, tipo),
  constraint rh_adm_resultado_so_aso check (resultado is null or tipo = 'aso_admissional'),
  constraint rh_adm_validade check (validade is null or data_item is null or validade >= data_item)
);
create index if not exists rh_adm_itens_pend on public.rh_admissao_itens (empresa_id, situacao) where situacao = 'pendente';
-- a categoria tem de bater com o tipo (exame não se disfarça de documento para fugir da trava de saúde)
create or replace function public.rh_adm_item_confere()
returns trigger language plpgsql set search_path to 'public' as $$
begin
  if (new.tipo in ('aso_admissional', 'audiometria', 'espirometria', 'raio_x_torax', 'acuidade_visual', 'hemograma', 'eletrocardiograma', 'eletroencefalograma', 'toxicologico', 'outro_exame_pcmso')) <> (new.categoria = 'exame') then
    raise exception 'Categoria % não combina com o item %', new.categoria, new.tipo using errcode = '23514';
  end if;
  new.updated_at := now(); new.updated_by := auth.uid();
  return new;
end $$;
drop trigger if exists rh_adm_item_confere on public.rh_admissao_itens;
create trigger rh_adm_item_confere before insert or update on public.rh_admissao_itens for each row execute function public.rh_adm_item_confere();
drop trigger if exists rh_adm_item_colab_empresa on public.rh_admissao_itens;
create trigger rh_adm_item_colab_empresa before insert or update of colaborador_id, empresa_id on public.rh_admissao_itens
  for each row execute function public.rh_confere_mesma_empresa('rh_colaboradores', 'colaborador_id');
alter table public.rh_admissao_itens enable row level security;
drop policy if exists rh_adm_le on public.rh_admissao_itens;
create policy rh_adm_le on public.rh_admissao_itens for select to authenticated
  using (case when categoria = 'exame' then public.rh_pode(empresa_id, 'saude') else public.rh_pode(empresa_id, 'pessoais') end);
drop policy if exists rh_adm_grava on public.rh_admissao_itens;
create policy rh_adm_grava on public.rh_admissao_itens for all to authenticated
  using (public.rh_pode(empresa_id, 'editar') and case when categoria = 'exame' then public.rh_pode(empresa_id, 'saude') else public.rh_pode(empresa_id, 'pessoais') end)
  with check (public.rh_pode(empresa_id, 'editar') and case when categoria = 'exame' then public.rh_pode(empresa_id, 'saude') else public.rh_pode(empresa_id, 'pessoais') end);
